def expand(query: str) -> set[str]:
    """返回查询里没出现、但同组其他词应该被加进去的那些原词（未切词）。"""
    q = query.lower()
    extra: set[str] = set()
    for group in ALIAS_GROUPS:
        # "~词"：只在同组别的词命中时才扩展，自己不做触发词。
        # 2026-10-24 加：她问「上下文压缩和自动注入」被安全组的「注入」拽去 913-安全墙，
        # 而「安全墙怎么防注入」靠「安全」照样能触发，所以把「注入」降成被动成员。
        triggers = [w for w in group if not w.startswith("~")]
        if any(word.lower() in q for word in triggers):
            extra.update(w.lstrip("~") for w in group)
    extra.update(_numeral_forms(q))
    return extra


# 中文数字 ↔ 阿拉伯数字（2026-10-21 补）：她嘴上写「一百五十行」，模块正文里写
# 「150 行」；bigram 切词下「一百五十」切成 一百/百五/五十，一个都对不上数字，
# 这条查询因此永远落空。反过来她要求（原话已移除）而正文写「一百五十」也一样。
_NUM_WORDS = {
    "零": 0, "一": 1, "二": 2, "两": 2, "三": 3, "四": 4, "五": 5,
    "六": 6, "七": 7, "八": 8, "九": 9,
}
_NUM_UNITS = {"十": 10, "百": 100, "千": 1000, "万": 10000}


def _cn2int(s: str) -> int | None:
    """把「一百五十」这种纯中文数字串转成整数；不是纯数字串就返回 None。"""
    if not s or any(ch not in _NUM_WORDS and ch not in _NUM_UNITS for ch in s):
        return None
    total, section, num = 0, 0, 0
    for ch in s:
        if ch in _NUM_WORDS:
            num = _NUM_WORDS[ch]
        else:
            unit = _NUM_UNITS[ch]
            if unit == 10000:
                total += (section + num) * unit
                section, num = 0, 0
            else:
                section += (num or 1) * unit
                num = 0
    val = total + section + num
    return val or None


def _numeral_forms(q: str) -> set[str]:
    """查询里出现的中文数字，补上等价的阿拉伯数字（只补数字本身，不补句式）。"""
    out: set[str] = set()
    for seg in re.findall(r"[零一二两三四五六七八九十百千万]+", q):
        v = _cn2int(seg)
        if v is not None:
            out.add(str(v))
    return out
